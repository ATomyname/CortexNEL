// Skip32Encrypt 对 32-bit 值做 Skip32 加密。
// 事实来源：docs/facts/NETEASE-PROTOCOL.md §2
// 「authId = int32-BE(Skip32(int32-BE(userId), "SaintSteve"))」。
func Skip32Encrypt(value uint32, key []byte) (uint32, error) {
	if len(key) != skip32KeyLen {
		return 0, errSkip32KeyLen
	}
	return skip32(value, key, true), nil
}

// Skip32Decrypt 对 32-bit 值做 Skip32 解密。
func Skip32Decrypt(value uint32, key []byte) (uint32, error) {
	if len(key) != skip32KeyLen {
		return 0, errSkip32KeyLen
	}
	return skip32(value, key, false), nil
}

// skip32 是 Skip32 核心：32-bit 块、80-bit 密钥、24 轮（12 轮双步）Feistel 网络。
// 实现对齐 Nirvana.Cipher 的 Skip32Cipher.cs（白名单参考实现）。
func skip32(value uint32, key []byte, encrypt bool) uint32 {
	// 拆成两个 16-bit 半块：wl = 高 16 位，wr = 低 16 位。
	wl := uint16(value >> 16)
	wr := uint16(value)

	step := 1
	k := 0
	if !encrypt {
		step = -1
		k = 23
	}

	for i := 0; i < 24/2; i++ {
		wr ^= skip32G(key, k, wl) ^ uint16(k)
		k += step
		wl ^= skip32G(key, k, wr) ^ uint16(k)
		k += step
	}

	// 输出时交换左右：buf[0..1] = wr，buf[2..3] = wl。
	return (uint32(wr) << 16) | uint32(wl)
}

// skip32G 是轮函数：4 次「查表 + 与前值异或」，返回 16-bit。
func skip32G(key []byte, k int, w uint16) uint16 {
	g1 := w >> 8
	g2 := w & 0xff

	g3 := uint16(skip32FTable[g2^uint16(key[(4*k)%10])]) ^ g1
	g4 := uint16(skip32FTable[g3^uint16(key[(4*k+1)%10])]) ^ g2
	g5 := uint16(skip32FTable[g4^uint16(key[(4*k+2)%10])]) ^ g3
	g6 := uint16(skip32FTable[g5^uint16(key[(4*k+3)%10])]) ^ g4

	return (g5 << 8) | g6
}
