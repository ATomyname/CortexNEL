// Package archive 只做一件事：把远端分发的压缩包安全地落到本地。
//
// 下载（带进度、ctx 可取消）、MD5 校验、按魔数分派 zip/7z 解压（含 zip-slip
// 与 Windows 名字空间防护）。
//
// 单独成包的理由：客户端本体/服务器组件（internal/install）与 JRE 分发包
// （internal/launcher）用的是同一套分发形态与同一套安全约束；复制两份很容易在
// 其中一份漏掉越界防护 —— 解压用户可影响内容的归档是典型的路径穿越面。
//
// 落盘对所有调用方的两条承诺：
//  1. 半份文件绝不顶着最终文件名留下 —— 下载与解压都先写临时文件，成功才改名；
//     失败时连临时文件一起清掉，目标要么是完整的、要么根本不存在。
//  2. 条目被放弃必须留痕 —— 少解出一个文件等同于装了个坏包，静默跳过会把故障
//     推迟到启动阶段才爆发，且不留任何线索。
//
// 按职责分文件，一个文件只承担一件事：
//
//	download.go    把远端字节拉到本地
//	checksum.go    完整性校验（MD5）
//	extract.go     解压编排：请求、格式分派、逐条目遍历、完整性策略
//	placement.go   单个条目落位：原子写与声明大小核对
//	targetpath.go  条目名 → 安全目标路径（越界与 Windows 名字空间策略）
package archive

// ProgressFunc 汇报进度。参数序恒定：done 在前、total 在后（total 为 0 表示未知）。
// 统一成一个具名类型是为了让调用方无法把顺序记反 —— 之前就出现过回调签名与
// 接收方参数序相反、导致进度百分比颠倒的情况。
type ProgressFunc func(done, total int64)
